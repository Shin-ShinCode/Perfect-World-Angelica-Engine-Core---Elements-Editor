def load_existing_word_glossary() -> dict[str, str]:
    source = ROOT / "verification/generate-pw-ptbr-elements.py"
    text = source.read_text(encoding="utf-8-sig")
    match = re.search(
        r'words\s*=\s*dict\(line\.split\("=",\s*1\)\s*for\s+line\s+in\s+"""(.*?)"""\.strip\(\)\.splitlines\(\)\)',
        text,
        re.S,
    )
    if not match:
        raise RuntimeError("Não foi possível ler o glossário de listas existente.")
    return {key.lower(): value for key, value in (line.split("=", 1) for line in match.group(1).splitlines() if "=" in line)}


def canonical(field: str) -> str:
    return re.sub(r"\d+", "#", field)


def translate_pattern(pattern: str, glossary: dict[str, str]) -> str:
    if pattern in SPECIAL:
        return SPECIAL[pattern]
    pattern = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", pattern)
    pattern = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", pattern)
    parts = pattern.split("_")
    capture = 0
    translated: list[str] = []
    phrases = sorted(PHRASES.items(), key=lambda pair: len(pair[0].split("_")), reverse=True)
    index = 0
    while index < len(parts):
        matched = None
        for source, target in phrases:
            phrase_parts = source.split("_")
            if [part.lower() for part in parts[index:index + len(phrase_parts)]] == phrase_parts:
                matched = (target, len(phrase_parts))
                break
        if matched:
            translated.append(matched[0])
            index += matched[1]
            continue
        part = parts[index]
        index += 1
        if part == "#":
            capture += 1
            translated.append(f"${capture}")
            continue
        key = part.lower()
        if key in glossary:
            value = glossary[key]
        elif key in PHRASES:
            value = PHRASES[key]
        else:
            value = glossary.get(key, key)
        translated.append(value)
    text = " ".join(translated)
    text = re.sub(r"\s+", " ", text).strip()
    text = re.sub(r"\bID (?:da|do) ID\b", "ID", text, flags=re.IGNORECASE)
    text = re.sub(r"\bRequisito nível (mínimo|máximo)\b", r"Nível \1 exigido", text, flags=re.IGNORECASE)
    text = re.sub(r"\bQuantidade uso por intervalo\b", "Usos por intervalo", text, flags=re.IGNORECASE)
    text = re.sub(r"\bArquivo gráfico\b", "Arquivo de efeito gráfico", text, flags=re.IGNORECASE)
    text = re.sub(r"\b(HP|MP|SP) mínimo\b", r"\1 mínimo", text, flags=re.IGNORECASE)
    return text[:1].upper() + text[1:]


def main() -> None:
    config = CFG.read_text(encoding="utf-8-sig").splitlines()
    payload = json.loads(CATALOG.read_text(encoding="utf-8-sig"))
    strings: dict[str, str] = payload["strings"]
    previous_report = json.loads(REPORT.read_text(encoding="utf-8-sig")) if REPORT.exists() else {}
    baseline_missing = previous_report.get("untranslated_fields_before_generation")
    generated_keys = set(previous_report.get("generated_pattern_keys", []))
    regexes = [re.compile("^" + re.escape(key).replace(r"\$", r"\d+") + "$") for key in strings if "$" in key]
    list_schemas: dict[int, list[str]] = {}
    for index, line in enumerate(config[:-3]):
        header = re.match(r"0*(\d+) - ", line)
        if header and int(header.group(1)) <= 311:
            list_id = int(header.group(1))
            list_schemas[list_id] = [field for field in config[index + 2].split(";") if field]

    missing: set[str] = set()
    for fields in list_schemas.values():
        for field in fields:
            if field in strings or any(regex.fullmatch(field) for regex in regexes):
                continue
            missing.add(field)

    families = sorted(
        {canonical(field) for field in missing}
        | {key.replace("$", "#") for key in generated_keys}
    )
    glossary = load_existing_word_glossary()
    glossary.update(PHRASES)
    glossary.update(WORDS)
    generated = 0
    for family in families:
        key = family.replace("#", "$")
        if key in strings and key not in generated_keys:
            continue
        strings[key] = translate_pattern(family, glossary)
        generated += 1
        generated_keys.add(key)

    payload["strings"] = dict(sorted(strings.items(), key=lambda pair: pair[0].casefold()))
    CATALOG.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    field_regexes = [re.compile("^" + re.escape(key).replace(r"\$", r"\d+") + "$") for key in strings if "$" in key]
    untranslated_after = {
        field for fields in list_schemas.values() for field in fields
        if field not in strings and not any(regex.fullmatch(field) for regex in field_regexes)
    }
    if not isinstance(baseline_missing, int) or baseline_missing == 0:
        baseline_report = ROOT / "verification/AUDITORIA-IDIOMA-CAMPOS-1-311-2026-10-22.md"
        baseline_match = re.search(r"\*\*(\d[\d.]*)\*\* ainda não possuem tradução", baseline_report.read_text(encoding="utf-8")) if baseline_report.exists() else None
        baseline_missing = int(baseline_match.group(1).replace(".", "")) if baseline_match else len(missing)

    source_tokens: set[str] = set()
    for family in families:
        tokenized = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", family)
        tokenized = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", tokenized)
        source_tokens.update(token.lower() for token in re.split(r"[_#$]+", tokenized) if token)
    untranslated_tokens = sorted(token for token in source_tokens if token not in glossary)

    result = {
        "reference": str(CFG.relative_to(ROOT)).replace("\\", "/"),
        "list_ids_requested": "1-311",
        "schemas_found": len(list_schemas),
        "schema_ids_missing": sorted(set(range(1, 312)) - set(list_schemas)),
        "distinct_fields_before_generation": len(set(field for fields in list_schemas.values() for field in fields)),
        "untranslated_fields_before_generation": baseline_missing if isinstance(baseline_missing, int) and baseline_missing > 0 else len(missing),
        "generated_field_patterns": generated,
        "generated_pattern_keys": sorted(generated_keys),
        "untranslated_fields_after_generation": len(untranslated_after),
        "unmapped_source_tokens": untranslated_tokens,
    }
    REPORT.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({key: value for key, value in result.items() if key != "generated_pattern_keys"}, ensure_ascii=False, indent=2))


